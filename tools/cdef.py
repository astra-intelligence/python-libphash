"""Turn libphash's public header into a CFFI ``cdef``.

``libphash.h`` is the whole public API, so the binding declares exactly what the
header declares instead of keeping a hand-written copy that drifts. The header is
written for this: its only conditional blocks are the include guard, the
``PH_API``/``PH_NODISCARD`` definitions and ``extern "C"`` under ``__cplusplus``. A full
C preprocessor would need a compiler with ``-E`` on every platform (MSVC's differs), so
this module handles that subset itself and fails loudly on anything outside it.

Macros become cdef constants: an integer literal is declared as is (and substituted
where a declaration uses it, e.g. an array size), an integer expression as
``#define NAME ...`` for CFFI to compute, a floating literal as ``static const double``.
String macros are left out: the version string comes from ``ph_version()``.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

_ATTRIBUTES = ("PH_API", "PH_NODISCARD")
_INT_LITERAL = re.compile(r"^(0[xX][0-9a-fA-F]+|[0-9]+)[uUlL]*$")
_FLOAT_LITERAL = re.compile(r"^[0-9]*\.[0-9]+([eE][-+]?[0-9]+)?[fF]?$")
_DIRECTIVE = re.compile(r"^\s*#\s*(\w+)\s*(.*)$")
_FUNCTION = re.compile(r"\b(ph_\w+)\s*\(")


def _strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.DOTALL)
    return re.sub(r"//[^\n]*", "", text)


def _lines(path: Path) -> list[str]:
    text = _strip_comments(path.read_text(encoding="utf-8"))
    return text.replace("\\\n", " ").splitlines()


class _Header:
    def __init__(self) -> None:
        self.int_macros: dict[str, str] = {}
        self.expr_macros: list[str] = []
        self.float_macros: list[str] = []
        self.declarations: list[str] = []

    def read(self, path: Path) -> None:  # noqa: PLR0912 -- a branch per directive
        guard: str | None = None
        # One entry per open conditional: True when its lines are C++-only and skipped.
        stack: list[bool] = []
        for lineno, line in enumerate(_lines(path), 1):
            where = f"{path.name}:{lineno}"
            m = _DIRECTIVE.match(line)
            if m:
                name, rest = m.group(1), m.group(2).strip()
                if name in ("if", "ifdef", "ifndef"):
                    if guard is None and name == "ifndef" and not stack:
                        guard = rest
                    stack.append(any(stack) or rest == "__cplusplus")
                elif name in ("else", "elif"):
                    if not stack:
                        raise ValueError(f"{where}: #{name} without #if")
                elif name == "endif":
                    if not stack:
                        raise ValueError(f"{where}: #endif without #if")
                    stack.pop()
                elif name == "include":
                    # phash_version.h is generated by libphash's CMake and absent from
                    # the source tree; its macros are not declared, ph_version() and
                    # ph_version_number() give the version at run time.
                    included = path.parent / rest.strip('"')
                    if len(stack) == 1 and rest.startswith('"') and included.exists():
                        self.read(included)
                elif name == "define" and len(stack) == 1:
                    self._define(rest, guard, where)
                continue
            if not line.strip() or any(stack[1:]):
                continue
            if len(stack) != 1:
                raise ValueError(
                    f"{where}: declaration outside the include guard: {line!r}"
                )
            self.declarations.append(line)

    def _define(self, rest: str, guard: str | None, where: str) -> None:
        name, _, value = rest.partition(" ")
        value = value.strip()
        if name == guard or "(" in name:
            return
        if not value:
            raise ValueError(f"{where}: empty macro {name}")
        if _INT_LITERAL.match(value):
            self.int_macros[name] = value
        elif _FLOAT_LITERAL.match(value):
            self.float_macros.append(name)
        elif value.startswith('"'):
            pass
        else:
            self.expr_macros.append(name)


def header_cdef(header: Path) -> str:
    """Return the cdef for ``header`` (``libphash.h``, next to ``phash_version.h``)."""
    h = _Header()
    h.read(header)
    body = "\n".join(h.declarations)
    body = re.sub(r"\bextern\s+\"C\"\s*\{", "", body)
    for attr in _ATTRIBUTES:
        body = re.sub(rf"\b{attr}\b", "", body)
    for name, value in h.int_macros.items():
        body = re.sub(rf"\b{name}\b", value, body)
    for name in h.expr_macros:
        if re.search(rf"\b{name}\b", body):
            raise ValueError(f"{name} is an expression macro used in a declaration")
    out = [f"#define {n} {v}" for n, v in h.int_macros.items()]
    out += [f"#define {n} ..." for n in h.expr_macros]
    out += [f"static const double {n};" for n in h.float_macros]
    out.append(body)
    return "\n".join(out) + "\n"


#: The batch callbacks: implemented in Python with @ffi.def_extern, so no executable
#: closure is created at run time (which ffi.callback would need), and the C functions
#: libphash calls, which enter them one at a time on a free-threaded CPython
#: (tools/ffi.py).
BATCH_CALLBACKS = """
extern "Python" int _libphash_should_continue(void *user_data);
extern "Python" void _libphash_on_progress(size_t done, size_t total, void *user_data);
int (*const _libphash_continue)(void *user_data);
void (*const _libphash_progress)(size_t done, size_t total, void *user_data);
"""


def binding_cdef(header: Path) -> str:
    """Return the cdef of ``libphash._native``: the header and the batch callbacks."""
    return header_cdef(header) + BATCH_CALLBACKS


def header_functions(header: Path) -> set[str]:
    """Names of the functions ``header`` declares."""
    h = _Header()
    h.read(header)
    names: set[str] = set()
    for decl in " ".join(h.declarations).split(";"):
        if "typedef" in decl:
            continue
        m = _FUNCTION.search(decl)
        if m:
            names.add(m.group(1))
    return names
