"""Generate ``src/libphash/_native.pyi``, the typed stub of the CFFI module.

The types come from the built module through cffi's own introspection (``ffi.typeof``,
``ffi.list_types``), so the stub states what the compiled extension accepts and
returns; the parameter names come from the cdef. Run after a build::

    python tools/stub.py            # write the stub
    python tools/stub.py --check    # exit 1 if the committed stub is out of date

The stub models cffi's rules for arguments, not just the C types:

- a ``T *`` parameter takes a ``T *`` or ``T[]`` cdata of exactly that type, or a
  ``void *`` (``ffi.NULL``); never ``None``, and never a pointer to another type of the
  same size (``size_t *`` for ``uint64_t *``);
- a pointer to a character type (``char``, ``uint8_t``) also takes ``bytes`` and the
  cdata of the other character types;
- a ``void *`` parameter takes any pointer, a function pointer field its function or
  ``ffi.NULL``.

Each ``T *`` and ``T[]`` the API can use gets a class (``T_ptr``, ``T_array``), and
``ffi.new()``, ``ffi.cast()`` and ``ffi.from_buffer()`` are overloaded on the literal
cdecl, spelled ``"T *"`` or ``"T[]"`` (``const`` allowed), so ``ffi.new("uint64_t *")``
is a ``uint64_t_ptr``.
"""

from __future__ import annotations

import keyword
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING

from cdef import binding_cdef
from native import HEADER

if TYPE_CHECKING:
    from collections.abc import Callable

    from libphash._native import CField, CType

ROOT = Path(__file__).resolve().parent.parent
STUB = ROOT / "src" / "libphash" / "_native.pyi"

_LINE = 88
_INDENT = "    "
_CHAR_LIKE = ("char", "int8_t", "uint8_t", "signed char", "unsigned char")
_FLOATS = ("float", "double")
_PROTOTYPE = re.compile(r"\b(\w+)\s*\(([^()]*)\)\s*;")
_FN_TYPEDEF = re.compile(r"\(\s*\*\s*(\w+)\s*\)\s*\(([^()]*)\)\s*;")

_HEAD = """\
# Generated by tools/stub.py from the built module; do not edit.
# Every function and constant of libphash.h, typed by cffi's argument rules.

from collections.abc import Callable, Iterator, Mapping, Sequence
from typing import Final, Literal, TypeVar, overload

from typing_extensions import Buffer

_P = TypeVar("_P", bound=Pointer)
_F = TypeVar("_F", bound=Callable[..., object])

class CData: ...

class Pointer(CData):
    def __bool__(self) -> bool: ...

class void_ptr(Pointer): ...

class CField:
    type: CType
    offset: int

class CType:
    kind: str
    cname: str
    item: CType
    length: int | None
    fields: list[tuple[str, CField]] | None
    args: tuple[CType, ...]
    result: CType
    ellipsis: bool
    elements: dict[int, str]

class CBuffer:
    def __buffer__(self, flags: int, /) -> memoryview: ...
    def __len__(self) -> int: ...
    @overload
    def __getitem__(self, index: int, /) -> bytes: ...
    @overload
    def __getitem__(self, index: slice, /) -> bytes: ...
"""


def _parameter_names(cdef: str) -> dict[str, list[str]]:
    """Return the parameter names of each function and function-pointer typedef."""
    text = " ".join(line for line in cdef.splitlines() if not line.startswith("#"))
    names: dict[str, list[str]] = {}
    for pattern in (_FN_TYPEDEF, _PROTOTYPE):
        for m in pattern.finditer(text):
            params = [p.strip() for p in m.group(2).split(",")]
            if params in ([""], ["void"]):
                params = []
            names.setdefault(m.group(1), [_param_name(p) for p in params])
    return names


def _param_name(declaration: str) -> str:
    words = re.findall(r"\w+", re.sub(r"\[.*?\]", "", declaration))
    name = words[-1] if len(words) > 1 else "arg"
    return name + "_" if keyword.iskeyword(name) else name


def _signature(
    indent: str, name: str, params: list[str], result: str, prefix: str = "def "
) -> list[str]:
    """Lay a stub signature out as ``ruff format`` does."""
    flat = f"{indent}{prefix}{name}({', '.join(params)}) -> {result}: ..."
    if len(flat) <= _LINE:
        return [flat]
    inner = indent + _INDENT
    joined = f"{inner}{', '.join(params)}"
    if len(joined) <= _LINE:
        return [f"{indent}{prefix}{name}(", joined, f"{indent}) -> {result}: ..."]
    lines = [f"{indent}{prefix}{name}("]
    for p in params:
        lines += _wrap_param(inner, p)
    return [*lines, f"{indent}) -> {result}: ..."]


def _wrap_param(indent: str, param: str) -> list[str]:
    line = f"{indent}{param},"
    if len(line) <= _LINE:
        return [line]
    # A Literal too long for one line: one member per line, as ruff splits it.
    m = re.fullmatch(r"(\w+): Literal\[(.*)\]", param)
    if m is None:
        raise ValueError(f"cannot lay out parameter {param!r}")
    members = [f"{indent}{_INDENT}{x.strip()}," for x in m.group(2).split(",")]
    return [f"{indent}{m.group(1)}: Literal[", *members, f"{indent}],"]


@dataclass
class _Stub:
    """The classes and members of the stub, collected from the module's types."""

    typeof: Callable[[str], CType]
    typedefs: dict[str, str]
    #: The fields of each struct by cname, empty for an opaque struct.
    fields: dict[str, list[tuple[str, CField]]]
    param_names: dict[str, list[str]]
    #: The pointer types the API uses.
    pointers: list[CType]
    classes: dict[str, list[str]] = field(default_factory=dict[str, list[str]])
    #: The item types ffi.new(), cast() and from_buffer() are typed for, by spelling.
    allocatable: dict[str, CType] = field(default_factory=dict[str, "CType"])

    # --- Names and types -----------------------------------------------------------

    def name(self, t: CType) -> str:
        """Return the stub class of a ctype, ``T_ptr`` for ``T *``."""
        if t.kind == "void":
            return "void"
        if t.kind in ("primitive", "enum"):
            return t.cname.replace(" ", "_")
        if t.kind == "pointer":
            return self.name(t.item) + "_ptr"
        if t.kind == "array":
            return self.name(t.item) + "_array"
        if t.kind in ("struct", "function"):
            alias = self.typedefs.get(t.cname)
            if alias is None:
                raise ValueError(f"{t.cname} has no typedef in libphash.h")
            return alias
        raise ValueError(f"unsupported ctype {t.cname} ({t.kind})")

    def cdecl(self, t: CType) -> str:
        """Return the C spelling of a ctype as the binding writes it."""
        if t.kind == "pointer":
            return self.cdecl(t.item) + " *"
        if t.kind in ("struct", "function"):
            return self.name(t)
        return t.cname

    def value(self, t: CType) -> str:
        """Return the Python type of a value of ``t`` read from C."""
        if t.kind == "enum":
            return "int"
        if t.kind == "primitive":
            if t.cname == "char":
                return "bytes"
            if t.cname == "_Bool":
                return "bool"
            return "float" if t.cname in _FLOATS else "int"
        if t.kind == "void":
            return "None"
        self.need(t)
        return self.name(t)

    def accept(self, t: CType, *, argument: bool = True) -> str:
        """Return what a parameter (or, with ``argument=False``, a field) takes."""
        if t.kind == "array":
            item = self.value(t.item)
            sequence = "bytes" if item == "bytes" else f"Sequence[{item}]"
            return f"{self.value(t)} | {sequence}"
        if t.kind == "function":
            return f"{self.value(t)} | void_ptr"
        if t.kind != "pointer":
            return self.value(t)
        if t.item.kind == "void":
            return "Pointer"
        if t.item.kind == "primitive" and t.item.cname in _CHAR_LIKE:
            chars = sorted(
                self.name(c)
                for c in self.pointers
                if c.item.kind == "primitive" and c.item.cname in _CHAR_LIKE
            )
            return " | ".join((["bytes"] if argument else []) + chars + ["void_ptr"])
        return f"{self.value(t)} | void_ptr"

    # --- Classes --------------------------------------------------------------------

    def need(self, t: CType) -> None:
        """Make sure the class of ``t`` (and of what it refers to) is emitted."""
        name = self.name(t)
        if name in self.classes or t.kind in ("primitive", "enum", "void"):
            return
        self.classes[name] = []  # placeholder against recursion
        if t.kind == "struct":
            self.classes[name] = self._struct(t, name)
        elif t.kind == "function":
            self.classes[name] = self._function(t, name)
        elif t.kind == "pointer":
            self.classes[name] = self._pointer(t, name)
        elif t.kind == "array":
            self.classes[name] = self._array(t, name)

    def _fields(self, t: CType) -> list[str]:
        out: list[str] = []
        for fname, f in self.fields[t.cname]:
            get, put = self.value(f.type), self.accept(f.type, argument=False)
            if get == put:
                out.append(f"{_INDENT}{fname}: {get}")
                continue
            out += [
                f"{_INDENT}@property",
                f"{_INDENT}def {fname}(self) -> {get}: ...",
                f"{_INDENT}@{fname}.setter",
                *_signature(_INDENT, fname, ["self", f"value: {put}"], "None"),
            ]
        return out

    def _struct(self, t: CType, name: str) -> list[str]:
        if not self.fields[t.cname]:
            return []  # opaque: only pointers to it exist
        return [f"class {name}(CData):", *self._fields(t)]

    def _function(self, t: CType, name: str) -> list[str]:
        names = self.param_names.get(name) or [f"arg{i}" for i in range(len(t.args))]
        params = [
            "self",
            *(f"{n}: {self.accept(a)}" for n, a in zip(names, t.args, strict=True)),
        ]
        result = self.value(t.result)
        return [
            f"class {name}(Pointer):",
            *_signature(_INDENT, "__call__", [*params, "/"], result),
        ]

    def _pointer(self, t: CType, name: str) -> list[str]:
        item = t.item
        if item.kind == "void":
            return []  # void_ptr is in the head
        if item.kind == "struct" and not self.fields[item.cname]:
            return [f"class {name}(Pointer): ..."]  # opaque: no members
        if item.kind != "function":
            self.allocatable[self.cdecl(item)] = item
        body = self._fields(item) if item.kind == "struct" else []
        get, put = self.value(item), self.accept(item, argument=False)
        body += [
            *_signature(_INDENT, "__add__", ["self", "offset: int", "/"], name),
            *_signature(_INDENT, "__getitem__", ["self", "index: int", "/"], get),
            *_signature(
                _INDENT,
                "__setitem__",
                ["self", "index: int", f"value: {put}", "/"],
                "None",
            ),
        ]
        return [f"class {name}(Pointer):", *body]

    def _array(self, t: CType, name: str) -> list[str]:
        pointer = self.typeof(t.item.cname + " *")
        self.need(pointer)
        item = self.value(t.item)
        return [
            f"class {name}({self.name(pointer)}):",
            f"{_INDENT}def __len__(self) -> int: ...",
            f"{_INDENT}def __iter__(self) -> Iterator[{item}]: ...",
        ]


def generate() -> str:
    """Return the text of the stub for the built ``libphash._native``."""
    from libphash._native import ffi, lib  # noqa: PLC0415 -- needs a built module

    typedef_names, _, _ = ffi.list_types()
    # "struct ph_context" -> "ph_context_t", "int(*)(void *)" -> "ph_batch_continue_fn".
    typedefs = {ffi.typeof(n).cname: n for n in typedef_names}

    names = sorted(dir(lib))
    functions = {
        n: ffi.typeof(getattr(lib, n)) for n in names if callable(getattr(lib, n))
    }
    constants = {n: getattr(lib, n) for n in names if n not in functions}

    # Every pointer type that appears, so that ffi.new() of its item is typed.
    seen: dict[str, CType] = {}
    fields: dict[str, list[tuple[str, CField]]] = {}

    def struct_fields(t: CType) -> list[tuple[str, CField]]:
        # CType.fields asserts that the struct is complete, and the cffi wheels for
        # Linux keep their assertions: on an opaque struct the interpreter aborts. An
        # opaque struct is the one ffi.sizeof() cannot measure.
        try:
            ffi.sizeof(t.cname)
        except ffi.error:
            return []
        return t.fields or []

    def visit(t: CType) -> None:
        if t.cname in seen:
            return
        seen[t.cname] = t
        if t.kind in ("pointer", "array"):
            visit(t.item)
            visit(ffi.typeof(t.item.cname + " *"))
        elif t.kind == "struct":
            fields[t.cname] = struct_fields(t)
            for _, f in fields[t.cname]:
                visit(f.type)
        elif t.kind == "function":
            for a in (*t.args, t.result):
                visit(a)

    for t in functions.values():
        visit(t)
    for n in typedef_names:
        visit(ffi.typeof(n))
    stub = _Stub(
        typeof=ffi.typeof,
        typedefs=typedefs,
        fields=fields,
        param_names=_parameter_names(binding_cdef(HEADER)),
        pointers=[t for t in seen.values() if t.kind == "pointer"],
    )
    for t in seen.values():
        # The prototypes of lib's functions are visited for their argument types only.
        if t.kind == "function" and t.cname not in typedefs:
            continue
        if t.kind in ("pointer", "array", "struct", "function"):
            stub.need(t)
    lib_body = _lib_body(stub, functions, constants)
    ffi_body = _ffi_body(stub)
    out = [_HEAD]
    for name in sorted(stub.classes, key=_class_order):
        lines = stub.classes[name]
        if not lines:
            continue
        # ruff format keeps one-line classes together, without a blank line between.
        last = out[-1].splitlines()[-1]
        if len(lines) == 1 and last.startswith("class ") and last.endswith(": ..."):
            out[-1] += lines[0] + "\n"
        else:
            out.append("\n".join(lines) + "\n")
    out.append("\n".join(["class _Lib:", *lib_body]) + "\n")
    out.append("\n".join(["class _FFI:", *ffi_body]) + "\n")
    out.append("ffi: _FFI\nlib: _Lib\n")
    return "\n".join(out)


def _class_order(name: str) -> tuple[str, int]:
    """Order a type's classes: the value, then ``_ptr``, then ``_array``."""
    for rank, suffix in enumerate(("_array", "_ptr")):
        if name.endswith(suffix):
            return (_class_order(name[: -len(suffix)])[0], 2 - rank)
    return (name, 0)


def _lib_body(
    stub: _Stub, functions: dict[str, CType], constants: dict[str, object]
) -> list[str]:
    body = [
        f"{_INDENT}{n}: Final[{type(v).__name__}]" for n, v in sorted(constants.items())
    ]
    for name, t in functions.items():
        if name.startswith("_"):  # an extern "Python" callback: a function pointer
            fn = stub.typedefs.get(t.cname)
            if fn is None:
                raise ValueError(f"callback {name} matches no typedef of libphash.h")
            body.append(f"{_INDENT}{name}: {fn}")
            continue
        names = stub.param_names[name]
        if len(names) != len(t.args):
            raise ValueError(f"{name}: {len(names)} names for {len(t.args)} arguments")
        params = [
            "self",
            *(f"{n}: {stub.accept(a)}" for n, a in zip(names, t.args, strict=True)),
        ]
        if t.args:
            params.append("/")
        body += _signature(_INDENT, name, params, stub.value(t.result))
    return body


def _ffi_body(stub: _Stub) -> list[str]:
    body = [f"{_INDENT}NULL: void_ptr", f"{_INDENT}error: type[Exception]"]
    new: list[str] = []
    cast: list[str] = []
    from_buffer: list[str] = []
    for cdecl, item in sorted(stub.allocatable.items()):
        ptr = stub.name(stub.typeof(item.cname + " *"))
        array_type = stub.typeof(item.cname + "[]")
        stub.need(array_type)
        array = stub.name(array_type)
        spell = [cdecl] if cdecl.endswith("*") else [cdecl, f"const {cdecl}"]
        ptrs = _literal([s + ("*" if s.endswith("*") else " *") for s in spell])
        arrays = _literal([s + "[]" for s in spell])
        value = stub.accept(item, argument=False)
        if item.kind == "struct":
            value = "Mapping[str, object] | Sequence[object]"
        elements = stub.value(item)
        sequence = "bytes" if elements == "bytes" else f"Sequence[{elements}]"
        new += _overload("new", [f"cdecl: {ptrs}", f"init: {value} = ...", "/"], ptr)
        new += _overload(
            "new", [f"cdecl: {arrays}", f"init: int | {sequence} = ...", "/"], array
        )
        cast += _overload("cast", [f"cdecl: {ptrs}", "value: int | Pointer", "/"], ptr)
        from_buffer += _overload(
            "from_buffer",
            [
                f"cdecl: {arrays}",
                "python_buffer: Buffer",
                "/",
                "require_writable: bool = ...",
            ],
            array,
        )
    cast += _overload(
        "cast", ['cdecl: Literal["void *"]', "value: int | Pointer", "/"], "void_ptr"
    )
    char_pointers = stub.accept(stub.typeof("char *"), argument=False)
    char_pointers = char_pointers.removesuffix(" | void_ptr")
    body += new + cast
    body += _overload(
        "from_buffer",
        ["python_buffer: Buffer", "/", "require_writable: bool = ..."],
        "char_array",
    )
    body += from_buffer
    body += _signature(
        _INDENT,
        "string",
        ["self", f"cdata: {char_pointers}", "maxlen: int = ..."],
        "bytes",
    )
    body += _signature(
        _INDENT, "buffer", ["self", "cdata: Pointer", "size: int = ..."], "CBuffer"
    )
    body += _signature(
        _INDENT,
        "memmove",
        ["self", "dest: Pointer | Buffer", "src: Pointer | Buffer", "n: int"],
        "None",
    )
    body += _signature(
        _INDENT,
        "gc",
        [
            "self",
            "cdata: _P",
            "destructor: Callable[[_P], object] | None",
            "size: int = ...",
        ],
        "_P",
    )
    body += _signature(_INDENT, "release", ["self", "cdata: Pointer", "/"], "None")
    body += _signature(_INDENT, "new_handle", ["self", "x: object", "/"], "void_ptr")
    body += _signature(_INDENT, "from_handle", ["self", "x: void_ptr", "/"], "object")
    body += _signature(
        _INDENT,
        "def_extern",
        [
            "self",
            "name: str = ...",
            "error: object = ...",
            "onerror: Callable[..., object] | None = ...",
        ],
        "Callable[[_F], _F]",
    )
    body += _signature(
        _INDENT,
        "typeof",
        ["self", "cdecl: str | CData | Callable[..., object]", "/"],
        "CType",
    )
    body += _signature(_INDENT, "sizeof", ["self", "cdecl: str | CData", "/"], "int")
    body += _signature(
        _INDENT, "list_types", ["self"], "tuple[list[str], list[str], list[str]]"
    )
    return body


def _literal(spellings: list[str]) -> str:
    return "Literal[" + ", ".join(f'"{s}"' for s in spellings) + "]"


def _overload(name: str, params: list[str], result: str) -> list[str]:
    return [
        f"{_INDENT}@overload",
        *_signature(_INDENT, name, ["self", *params], result),
    ]


def main(argv: list[str]) -> int:
    """Write the stub, or with ``--check`` compare it with the committed one."""
    text = generate()
    if "--check" in argv:
        if STUB.read_text(encoding="utf-8") != text:
            print(f"{STUB} is out of date; run python tools/stub.py", file=sys.stderr)  # noqa: T201
            return 1
        return 0
    STUB.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
